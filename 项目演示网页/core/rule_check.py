import re
from collections import defaultdict

def run_rule_check(text):
    # 文本预处理：去除所有空格和换行，统一匹配
    text = text.replace(" ", "").replace("\n", "")
    clues = []

    # ==============================================
    # 第一类：负向特征监测（有因无果判定）
    # ==============================================

    # 监督点1：公告费裁判不当（2个子项）
    # 子项1：有公告送达但未裁判公告费
    if "公告送达" in text and "公告费" not in text:
        clues.append({
            "问题": "采用公告送达但未对公告费事项进行裁判",
            "风险等级": "中风险",
            "法律依据": "《诉讼费用交纳办法》第29条",
            "初步评估": "裁判主文遗漏法定诉讼费用事项，属于文书制作瑕疵",
            "检察建议": "在判决主文中补全公告费承担事项"
        })
    # 子项2：公告费承担方式不规范（直接支付给原告）
    if "公告费" in text and ("直接支付" in text or "径向" in text or "支付给" in text):
        clues.append({
            "问题": "公告费承担方式表述不规范",
            "风险等级": "中风险",
            "法律依据": "《诉讼费用交纳办法》第52条",
            "初步评估": "裁判主文书写不标准，违反诉讼费用收缴规定",
            "检察建议": "修改为‘公告费由被告负担’，禁止直接支付给原告"
        })

    # 监督点2：一般保证人履行顺位未明确
    if "一般保证责任" in text and "保证人仅对债务人财产依法强制执行后仍不能履行的部分承担保证责任" not in text:
        clues.append({
            "问题": "判决书主文未明确一般保证人履行顺位",
            "风险等级": "高风险",
            "法律依据": "《民法典》第687条",
            "初步评估": "实体裁判错误，可能导致保证人权利受损",
            "检察建议": "在判决主文中明确一般保证人的先诉抗辩权"
        })

    # 监督点3：合同解除时间认定错误
    if re.search(r"第五百六十三条|第563条|第五百六十五条|第565条", text) and "判决生效之日解除" in text:
        clues.append({
            "问题": "合同法定解除情形下错误认定解除时间为判决生效之日",
            "风险等级": "高风险",
            "法律依据": "《民法典》第565条",
            "初步评估": "法律适用错误，合同解除时间应溯及到通知到达之日",
            "检察建议": "纠正合同解除时间的认定"
        })

    # 监督点10：金钱给付判决未载明加倍迟延履行利息
    if re.search(r"民间借贷纠纷|买卖合同纠纷", text) and re.search(r"支付|给付|偿还", text) and "加倍支付迟延履行期间债务利息" not in text:
        clues.append({
            "问题": "涉金钱给付义务判决未载明加倍迟延履行利息",
            "风险等级": "高风险",
            "法律依据": "《民事诉讼法》第264条",
            "初步评估": "裁判主文遗漏法定必备条款，损害债权人合法权益",
            "检察建议": "在判决主文末尾补全加倍利息表述"
        })

    # ==============================================
    # 第二类：正向程序冲突（刚性布尔冲突判定）
    # ==============================================

    # 监督点4：小额诉讼程序再审审级不当
    if "再审裁定书" in text and re.search(r"\(.*\).*申.*号", text) and ("中级人民法院" in text or "中院" in text) and "小额诉讼程序" in text:
        clues.append({
            "问题": "小额诉讼程序案件再审法院层级不当",
            "风险等级": "高风险",
            "法律依据": "《民事诉讼法司法解释》第424条",
            "初步评估": "审判程序严重违法，违反小额诉讼再审管辖规定",
            "检察建议": "应由基层人民法院进行再审"
        })

    # 监督点5：诉讼费用收取不符合法律规定
    if "案件受理费" in text and ("直接支付" in text or "径向" in text or "支付给" in text):
        clues.append({
            "问题": "直接判决案件受理费由败诉方向胜诉方支付",
            "风险等级": "中风险",
            "法律依据": "《诉讼费用交纳办法》第52条",
            "初步评估": "诉讼费用收缴程序不规范",
            "检察建议": "修改为‘案件受理费由被告负担’，由法院统一收缴退还"
        })

    # 监督点6：简易程序不当适用公告送达
    # 先提取判决年份，判断是否为2023年及以后
    year_match = re.search(r"二〇(二三|二四|二五|二六)|2023|2024|2025|2026", text)
    if year_match:
        year = int(year_match.group().replace("二〇", "20").replace("二三", "23").replace("二四", "24").replace("二五", "25").replace("二六", "26"))
        if year >= 2023 and "简易程序" in text and "公告送达" in text and "转为普通程序" not in text:
            clues.append({
                "问题": "简易程序违法适用公告送达",
                "风险等级": "高风险",
                "法律依据": "2023年《民事诉讼法司法解释》第257条",
                "初步评估": "审判程序严重违法，属于重点监督情形",
                "检察建议": "应转为普通程序后再进行公告送达"
            })

    # 监督点9：民事判决书制作不规范
    if re.search(r"原告诉称|被告辩称|诉辩意见", text) and not re.search(r"证据交换|质证|提交了证据", text):
        clues.append({
            "问题": "民事判决书制作不规范，未载明证据质证环节",
            "风险等级": "中风险",
            "法律依据": "《人民法院民事裁判文书制作规范》",
            "初步评估": "文书格式不符合规范要求",
            "检察建议": "补全证据交换与质证部分的表述"
        })

    return clues

