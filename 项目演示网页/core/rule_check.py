# 【新增】第三类：跨案聚类分析（批量统计函数）
# ==============================================
def run_cross_case_analysis(task_list):
    """
    输入：批量解析后的 task_list
    输出：跨案分析结果（监督点7、8）
    """
    juror_count = defaultdict(int)
    agent_count = defaultdict(int)
    cross_case_clues = []

    for task in task_list:
        if "info" not in task:
            continue
        info = task["info"]
        
        # 监督点7：统计人民陪审员参审次数
        # 假设 info 里有 '人民陪审员' 字段（如果没有，可以从 text 里正则提取）
        if "人民陪审员" in info:
            jurors = info["人民陪审员"]
            if isinstance(jurors, str):
                jurors = [jurors]
            for j in jurors:
                if j:
                    juror_count[j] += 1

        # 监督点8：统计公民代理次数
        # 假设 info 里有 '委托诉讼代理人' 或 '辩护人' 字段
        if "委托诉讼代理人" in info:
            agents = info["委托诉讼代理人"]
            if isinstance(agents, str):
                agents = [agents]
            for a in agents:
                if a and ("律师" not in a and "法律工作者" not in a):
                    agent_count[a] += 1

    # 生成监督点7线索
    for name, cnt in juror_count.items():
        if cnt >= 30:
            cross_case_clues.append({
                "问题": f"人民陪审员 {name} 参审次数异常（{cnt}件/年）",
                "风险等级": "高风险",
                "法律依据": "《人民陪审员法》第16条",
                "初步评估": "人民陪审员参与案件审理不规范，可能存在职业化倾向",
                "检察建议": "调整该陪审员参审安排，确保参审均衡"
            })

    # 生成监督点8线索
    for name, cnt in agent_count.items():
        if cnt >= 5:
            cross_case_clues.append({
                "问题": f"公民代理人 {name} 代理次数异常（{cnt}次）",
                "风险等级": "高风险",
                "法律依据": "《民事诉讼法》第61条",
                "初步评估": "个别公民代理人职业化倾向明显",
                "检察建议": "核查该代理人身份资质，规范公民代理行为"
            })

    return cross_case_clues