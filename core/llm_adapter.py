import requests
import json
import re

def llm_analyze(text):
    prompt = f"""
你是专业的民事裁判文书解析助手。严格遵循以下规则：

【总规则】
1. 只能从给定的文本中提取信息，严禁编造、推测、补充任何文本中不存在的内容。
2. 如果某个字段在文本中完全找不到，必须输出"未提取"，不能输出任何近似值或推测值。
3. 只输出JSON，不要任何解释、说明、备注。
4. JSON必须完全符合指定格式，键名不能改。
5. 绝对不要输出```json、```、markdown、任何多余文字！只输出纯JSON！

【补充规则】
- 文书中的表格字段（如"审 理 法 院：..."），请先忽略字段名中的空格，再按“字段名:值”的格式提取内容。

【各字段提取规则】

1. 案号
- 案号只在文书首部查找（通常是标题右下方，格式如"(2025)京0105民初69761号"）。
- 必须带括号和年份，只输出案号本身。
- 如果没有找到这种格式的字符串，输出"未提取"。
- 严禁把执行案号（如"执1335号"）当成案号。

2. 审理法院
- 只在文书首部查找（通常在案号下方或标题位置）。
- 只输出法院全称，如"北京市朝阳区人民法院"。
- 如果没有明确写明审理法院，输出"未提取"，严禁自行推断。

3. 案由
- 案由通常在"原告xxx与被告xxx...纠纷"的表述中。
- 只输出纠纷类型本身，如"买卖合同纠纷""执行异议之诉"。
- 严禁把当事人姓名拼凑成案由，严禁输入超长字符。

4. 原告
- 在"原告"或"原告人"段落中查找。
- 只输出姓名或公司简称，多个原告用中文顿号"、"分隔。
- 严禁把被告、第三人、委托代理人错误输出为原告。

5. 被告
- 在"被告"或"被告人"段落中查找。
- 只输出姓名或公司简称，多个被告用中文顿号"、"分隔。
- 严禁把原告、第三人、委托代理人错误输出为被告。

6. 审判程序
- 在"审理经过"或"审判程序"描述段落中查找。
- 输出格式如"一审普通程序""二审程序""简易程序"等。
- 如果没有明确描述，输出"未提取"。

7. 公告送达
- 在全文检索"公告送达""公告期限""视为送达"等相关表述。
- 有就输出"是"，没有就输出"否"。

8. 立案日期
- 严格限制在"立案"相关语句中提取，如"于XXXX年XX月XX日立案"。
- 日期格式化为"YYYY年MM月DD日"，找不到即"未提取"。
- 严禁把判决日期、开庭日期误作为立案日期输出。

9. 开庭日期
- 严格限制在"公开开庭审理"或"开庭"相关语句中提取。
- 日期格式化为"YYYY年MM月DD日"，找不到即"未提取"。

10. 判决日期
- 只在文书末尾查找，通常是落款日期或"于XXXX年XX月XX日作出判决"的表述。
- 日期格式化为"YYYY年MM月DD日"，找不到即"未提取"。

11. 审判员
- 只在文书末尾的署名区域提取。
- 通常会独立成行，如"审判员：张三"或"审判长：李四"。
- 多个姓名用顿号"、"分隔，找不到输出"未提取"。

12. 书记员
- 只在文书末尾的署名区域提取。
- 通常会独立成行，如"书记员：王五"。
- 多个姓名用顿号"、"分隔，找不到输出"未提取"。

13. 裁判主文
- 在"判决如下"或"裁定如下"部分提取核心判决内容。
- 严格控制在100字以内。
- 如果未明确标注，输出"未提取"。

【输出格式】
严格按照以下JSON输出，键名一个不能改：
{{
  "案号": "xxx",
  "审理法院": "xxx",
  "案由": "xxx",
  "原告": "xxx",
  "被告": "xxx",
  "审判程序": "xxx",
  "公告送达": "xxx",
  "立案日期": "xxx",
  "开庭日期": "xxx",
  "判决日期": "xxx",
  "审判员": "xxx",
  "书记员": "xxx",
  "裁判主文": "xxx"
}}

文书内容：
{text[:9000]}
"""
    try:
        resp = requests.post(
            url="https://open.bigmodel.cn/api/paas/v4/chat/completions",
            headers={
                "Content-Type": "application/json",
                "Authorization": "Bearer b81aa49fd83549d6830c2175b226f2d0.ZOngwZ89PUMvILYf"
            },
            json={
                "model": "glm-4-flash",
                "messages": [{"role": "user", "content": prompt}],
                "temperature": 0.0
            }
        )
        resp.raise_for_status()
        data = resp.json()
        choices = data.get("choices", [])
        if not choices:
            return {"错误": "大模型返回异常，未找到choices字段"}

        message = choices[0].get("message", {})
        content = message.get("content", "")

        if not content:
            return {"错误": "大模型返回内容为空"}

        # 自动清洗JSON格式（移除markdown标记和多余空格）
        content = re.sub(r"```json|```", "", content).strip()

        try:
            return json.loads(content)
        except json.JSONDecodeError:
            return {"错误": "解析失败", "原始内容": content}

    except requests.exceptions.RequestException as e:
        return {"错误": f"网络请求失败：{str(e)}"}
    except Exception as e:
        return {"错误": f"未知错误：{str(e)}"}
